/**
 * test-generate-pages — example and regression-test plugin for the onGeneratePages hook.
 *
 * Demonstrates how a plugin can:
 *  - reserve a top-level route segment so Webette auto-renames any conflicting entry/collection
 *  - generate arbitrary static pages via ctx.renderPage at build time
 *
 * Generated pages:
 *  /demo-plugin/           — a simple index page
 *  /demo-plugin/sub-page/  — a sub-page to show nested routes work
 *
 * To trigger the slug-collision warning, create an entry or collection named "demo-plugin"
 * in this website-example and run a build — you will see a rename warning in the logs.
 */

export default {
  pluginId: "test-generate-pages",

  onInit(ctx) {
    ctx.addReservedRoute("demo-plugin");
    ctx.logger.info("plugin.testGeneratePages.reserved", { segment: "demo-plugin" });
  },

  async onGeneratePages(site, ctx) {
    const { renderPage } = ctx;

    await renderPage({
      route: "/demo-plugin/",
      layoutName: "entry",
      context: {
        entry: {
          name: "Demo Plugin — Index",
          route: "/demo-plugin/",
        },
        blocks: [
          {
            id: "demo-intro",
            type: "markdown",
            name: "intro",
            content: {
              html: "<p>This page was generated by the <strong>test-generate-pages</strong> plugin via <code>onGeneratePages</code>.</p>",
            },
          },
        ],
      },
    });

    await renderPage({
      route: "/demo-plugin/sub-page/",
      layoutName: "entry",
      context: {
        entry: {
          name: "Demo Plugin — Sub-page",
          route: "/demo-plugin/sub-page/",
        },
        blocks: [
          {
            id: "demo-sub",
            type: "markdown",
            name: "sub",
            content: {
              html: "<p>Sub-page generated by the <strong>test-generate-pages</strong> plugin.</p>",
            },
          },
        ],
      },
    });

    ctx.logger.info("plugin.testGeneratePages.generated", {
      pages: ["/demo-plugin/", "/demo-plugin/sub-page/"],
    });
  },
};
