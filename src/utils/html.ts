/**
 * HTML entity escaping for safe attribute and content interpolation.
 */

/** Escape a string for safe use in HTML attributes and content. */
export function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
